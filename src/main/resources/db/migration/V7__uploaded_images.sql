-- 업로드한 사진 기록. 누가 올린 사진인지 확인하고, 나중에 저장소에서 지울 때 사용한다.
CREATE TABLE uploaded_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    public_id VARCHAR(2048) NOT NULL UNIQUE,
    url VARCHAR(2048) NOT NULL UNIQUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_uploaded_images_user ON uploaded_images(user_id);

-- 이미 저장된 사진은 지금 그 주소를 쓰는 사용자를 주인으로 기록한다.
-- 업로드 API가 만드는 형식의 주소만 옮긴다. 같은 사진을 여러 사용자가 쓰고 있으면 사용자 번호가 가장 작은 쪽이 주인이다.
INSERT INTO uploaded_images (user_id, public_id, url)
SELECT DISTINCT ON (public_id) user_id, public_id, url
FROM (
    SELECT user_id, url,
           COALESCE(
               substring(url FROM '^https://res\.cloudinary\.com/[^/?#]+/image/upload/v[0-9]+/(petroad/(?:walk_photo|course_cover|dog_profile)/[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12})\.(?:jpg|png|webp)$'),
               substring(url FROM '^https?://[^?#]+/uploads/((?:walk_photo|course_cover|dog_profile)/[0-9a-f]{8}-(?:[0-9a-f]{4}-){3}[0-9a-f]{12}\.(?:jpg|png|webp))$')
           ) AS public_id
    FROM (
        SELECT user_id, profile_image AS url FROM dog
        UNION
        SELECT user_id, cover_image_url FROM course
        UNION
        SELECT user_id, cover FROM walk_log
        UNION
        SELECT walk_log.user_id, walk_log_photos.photo_url
        FROM walk_log
        JOIN walk_log_photos ON walk_log_photos.walk_log_id = walk_log.id
    ) used_images
) candidates
WHERE user_id IS NOT NULL AND public_id IS NOT NULL
ORDER BY public_id, user_id, url;
